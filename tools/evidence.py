#!/usr/bin/env python3
"""Narrow, stdlib-only reproducibility/consistency demonstration; see docs/workflow.md."""
import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path
import re
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
PRODUCTS = ('results.json', 'macros_results.tex', 'comparison_table.tex')

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def calculate(config, broken=False):
    if (config['integrand'], config['lower'], config['upper']) != ('x_squared', 0, 1):
        raise ValueError('demo supports only integral of x squared on [0,1]')
    n = config['panels']
    if isinstance(n, bool) or not isinstance(n, int) or n < 1 or n > 100000:
        raise ValueError('invalid panel count')
    tolerance = config['absolute_tolerance']
    if not isinstance(tolerance, (float, int)) or not 0 < tolerance < 1:
        raise ValueError('invalid tolerance')
    estimate = sum((Fraction(2*i+1, 2*n)**2 for i in range(n)), Fraction(0))/n
    if broken:
        estimate *= 2
    reference = Fraction(1,3)  # independent antiderivative: [x^3/3]_0^1
    error = abs(estimate-reference)
    if error > Fraction(str(tolerance)):
        raise ValueError('numerical acceptance failed')
    return {'IntegralEstimate':float(estimate), 'IntegralReference':float(reference),
            'IntegralError':float(error), 'IntegralTolerance':tolerance}

def generate(root, destination):
    config = json.loads((root/'cases/tooling/input.json').read_text())
    values = calculate(config)
    record = {'schema_version':1, 'scope':'synthetic integral, not an astrophysical result',
              'command':'python3 tools/evidence.py generate',
              'inputs':{'cases/tooling/input.json':digest(root/'cases/tooling/input.json')},
              'producer':{'tools/evidence.py':digest(root/'tools/evidence.py')},
              'environment':'Python 3.10+ standard library; exact rational quadrature',
              'seed':None, 'seed_reason':'deterministic, no random sampling',
              'units':'dimensionless', 'values':values}
    destination.mkdir(parents=True, exist_ok=True)
    (destination/'results.json').write_text(json.dumps(record,sort_keys=True,indent=2)+'\n')
    tex = '% GENERATED by tools/evidence.py; source hashes in results.json\n'
    tex += r'\newcommand{\result}[1]{\ifcsname result#1\endcsname\csname result#1\endcsname\else\PackageError{results}{Undefined result #1}{}\fi}'+'\n'
    for name,value in sorted(values.items()):
        tex += '\\expandafter\\def\\csname result'+name+'\\endcsname{'+format(value,'.8f')+'}\n'
    (destination/'macros_results.tex').write_text(tex)
    (destination/'comparison_table.tex').write_text(r"""\begin{tabular}{lr}
\toprule
Quantity & Value (dimensionless)\\
\midrule
Midpoint estimate & $\result{IntegralEstimate}$\\
Antiderivative reference & $\result{IntegralReference}$\\
Absolute discrepancy & $\result{IntegralError}$\\
Acceptance threshold & $\result{IntegralTolerance}$\\
\bottomrule
\end{tabular}
""")

def check(root):
    with tempfile.TemporaryDirectory() as directory:
        temp = Path(directory)
        generate(root, temp)
        for name in PRODUCTS:
            path = root/'paper/generated'/name
            if not path.is_file() or path.read_bytes() != (temp/name).read_bytes():
                raise ValueError('stale or corrupt generated artifact: '+name)
    source = (root/'paper/main.tex').read_text()
    # Restricted authored-source contract: no additional includes or embedded data.
    # Permit whitespace/comment-separated braced includes, then require every
    # include command to be recognized. Unbraced and conditional forms are outside
    # this deliberately restricted grammar.
    include_source = re.sub(r'(?m)(?<!\\)%[^\n]*', '', source)
    commands = re.findall(r'\\(?:input|include)\b', include_source)
    includes = re.findall(r'\\(?:input|include)\s*\{([^}]+)\}', include_source)
    if len(commands) != len(includes):
        raise ValueError('unsupported TeX source contract syntax')
    if sorted(includes) != ['generated/comparison_table.tex','generated/macros_results.tex']:
        raise ValueError('unexpected TeX source contract')
    if re.search(r'\\(?:includegraphics|InputIfFileExists|IfFileExists|newcommand|def|csname|catcode|write|openout)\b',source):
        raise ValueError('unsupported TeX construction; extend checker before use')
    values = json.loads((root/'paper/generated/results.json').read_text())['values']
    source = re.sub(r'\\verb(.).*?\1', '', source)
    uses = set(re.findall(r'\\result\{([^}]+)\}',source))
    table = (root/'paper/generated/comparison_table.tex').read_text()
    uses.update(re.findall(r'\\result\{([^}]+)\}',table))
    if uses-set(values):
        raise ValueError('undefined result key: '+str(sorted(uses-set(values))))
    # Citation-key integrity is mechanical; source existence and relevance require retrieval.
    definitions = re.findall(r'\\bibitem(?:\[[^]]*\])?\{([^}]+)\}', source)
    if len(definitions) != len(set(definitions)):
        raise ValueError('duplicate bibliography key')
    cited = set()
    for group in re.findall(r'\\cite(?:t|p)?\{([^}]+)\}', source):
        cited.update(key.strip() for key in group.split(','))
    if cited-set(definitions):
        raise ValueError('undefined citation key: '+str(sorted(cited-set(definitions))))
    # Approved structural constants and bibliographic metadata are not measured results.
    # No regex checker is a proof for unrestricted TeX.
    clean = re.sub(r'(?m)(?<!\\)%.*$', '', source)
    clean = re.sub(r'\\href\{[^}]*\}', '', clean)  # URL targets are identifiers, not printed results
    clean = re.sub(r'\\cite(?:t|p)?\{[^}]*\}', '', clean)  # checked citation identifiers
    clean = re.sub(r'\\date\{[^}]*\}', '', clean)
    clean = clean.replace(r'\documentclass[aps,prd,reprint,nofootinbib]{revtex4-2}', '')
    clean = re.sub(r'\\begin\{thebibliography\}\{[^}]*\}.*?\\end\{thebibliography\}', '', clean, flags=re.S)
    clean = clean.replace(r'I=\int_{0}^{1}x^2\,\mathrm{d}x', '')  # mathematical specification, not a computed result
    if re.search(r'\d',clean):
        raise ValueError('bare numeric literal in authored manuscript; use words for exposition and generated keys for results')
    print('PASS: regenerated artifacts match; result keys and restricted manuscript checked')

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action',choices=['generate','check'])
    args=parser.parse_args()
    try:
        if args.action=='generate': generate(ROOT,ROOT/'paper/generated')
        else: check(ROOT)
    except (ValueError, KeyError, OSError, json.JSONDecodeError) as error:
        print('FAIL:',error,file=sys.stderr)
        return 1
    return 0

if __name__=='__main__':
    raise SystemExit(main())
