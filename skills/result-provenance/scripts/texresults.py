#!/usr/bin/env python3
"""Portable result logger adapted from research-skills/paper-style.

Use ResultsLog(path, run=manifest); set a scalar or ordered interval with a
producer source, then write generated TeX and raw JSON together. The manifest
records completed work, code/environment identities, command, configuration,
input identifiers/hashes and scientific scope. This validates declared records
and generated bytes, not whether the scientific calculation was correct.
"""

import argparse
import copy
import hashlib
import math
import datetime
import json
import os
import re
import sys
from pathlib import Path

HEADER = r"""%% macros_results.tex -- GENERATED FILE, do not hand-edit.
%% Regenerate from the producing analysis and its completed-run manifest.
%% Only explicit \result{Name} access is supported; result names are namespaced.
\newcommand\result[1]{%
  \ifcsname TASresult@#1\endcsname\csname TASresult@#1\endcsname\else\textbf{??#1??}\fi}
"""

NAME_RE = re.compile(r"^[A-Za-z]+$")


def _fmt_value(value, fmt):
    if fmt is None:
        return str(value)
    return format(float(value), fmt)


class ResultsLog:
    """Read-modify-write interface to a macros_results.tex file.

    Entries are stored as an ordered dict name -> dict(latex, provenance).
    A JSON sidecar (macros_results.json) preserves raw values and metadata
    so results remain machine-readable for tables and cross-checks.
    """

    def __init__(self, path="macros_results.tex", run=None):
        self.path = str(path)
        self.run = copy.deepcopy(run)
        self.json_path = os.path.splitext(path)[0] + ".json"
        self.entries = {}
        if os.path.exists(self.json_path):
            with open(self.json_path) as f:
                self.entries = json.load(f)

    def _provenance(self, source, data):
        return {
            "source": str(source) if source else "unknown",
            "source_sha256": hashlib.sha256(Path(source).read_bytes()).hexdigest() if source and os.path.isfile(source) else None,
            "run": copy.deepcopy(self.run),
            "data": data,
            "date": datetime.datetime.now().strftime("%Y-%m-%d %H:%M"),
        }

    def set(self, name, value, fmt=None, unit=None, source=None, data=None):
        """Log a scalar; displayed text is derived only from its raw value."""
        if not NAME_RE.fullmatch(name):
            raise ValueError("result name must be alphabetic")
        self.entries[name] = {
            "kind": "scalar", "value": value, "fmt": fmt, "unit": unit,
            **self._provenance(source, data),
        }

    def set_interval(self, name, median, lo, hi, fmt=None, unit=None,
                     source=None, data=None):
        """Log an ordered median/interval; no custom display override."""
        if not NAME_RE.fullmatch(name):
            raise ValueError("result name must be alphabetic")
        if not float(lo) <= float(median) <= float(hi):
            raise ValueError("interval must satisfy lo <= median <= hi")
        self.entries[name] = {
            "kind": "interval", "value": [median, lo, hi], "fmt": fmt, "unit": unit,
            **self._provenance(source, data),
        }

    @staticmethod
    def display(entry):
        if entry["kind"] == "interval":
            median, lo, hi = entry["value"]
            m = _fmt_value(median, entry.get("fmt"))
            up = _fmt_value(hi - median, entry.get("fmt"))
            dn = _fmt_value(median - lo, entry.get("fmt"))
            body = f"{m}^{{+{up}}}_{{-{dn}}}"
        else:
            body = _fmt_value(entry["value"], entry.get("fmt"))
        return body + (entry.get("unit") or "")

    def validate(self):
        if not self.entries:
            raise ValueError("empty result record")
        for name, entry in self.entries.items():
            if not NAME_RE.fullmatch(name):
                raise ValueError("invalid result name")
            if entry.get("kind") not in {"scalar", "interval"}:
                raise ValueError("unknown result kind")
            if entry.get("fmt") is not None and not re.fullmatch(r"\.\d{1,2}[feg]", entry["fmt"]):
                raise ValueError("use an explicit decimal rounding format such as .2f or .3g")
            if entry.get("unit") is not None and not isinstance(entry["unit"], str):
                raise ValueError("unit must be trusted LaTeX text")
            if "latex" in entry:
                raise ValueError("custom display overrides are unsupported")
            values = entry.get("value")
            if (entry["kind"] == "interval") != isinstance(values, list):
                raise ValueError("result kind and value shape disagree")
            for value in values if isinstance(values, list) else [values]:
                if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
                    raise ValueError("results must be finite numerical values")
            if isinstance(values, list) and (len(values) != 3 or not values[1] <= values[0] <= values[2]):
                raise ValueError("invalid interval record")
            if not entry.get("source") or entry["source"] == "unknown" or not re.fullmatch(r"[0-9a-f]{64}", entry.get("source_sha256") or ""):
                raise ValueError("producer source and content hash required")
            run = entry.get("run")
            if not isinstance(run, dict) or run.get("completed") is not True:
                raise ValueError("completed run manifest required")
            for field in ("command", "code_revision", "environment", "scope"):
                if not run.get(field):
                    raise ValueError("missing run identity: " + field)
            if not isinstance(run.get("configuration"), dict):
                raise ValueError("effective configuration object required")
            inputs = run.get("inputs")
            if not isinstance(inputs, list) or not inputs:
                raise ValueError("input identities required; identify an analytic specification explicitly")
            for item in inputs:
                if not isinstance(item, dict) or not item.get("id") or not re.fullmatch(r"[0-9a-f]{64}", item.get("sha256") or ""):
                    raise ValueError("input id and sha256 required")

    def render(self):
        self.validate()
        lines = [HEADER]
        for name, e in sorted(self.entries.items()):
            prov = f"%% {name}: {e.get('source')}"
            if e.get("data"):
                prov += f"  data={e['data']}"
            prov += f"  [{e.get('date')}]"
            lines.append(prov)
            lines.append(
                f"\\expandafter\\newcommand\\csname TASresult@{name}\\endcsname"
                f"{{\\ensuremath{{{self.display(e)}}}}}")
        return "\n".join(lines) + "\n"

    def write(self):
        rendered = self.render()
        with open(self.path, "w") as f:
            f.write(rendered)
        with open(self.json_path, "w") as f:
            json.dump(self.entries, f, indent=1)


def _cmd_set(args):
    log = ResultsLog(args.file, run=json.loads(Path(args.run).read_text()) if args.run else None)
    log.set(args.name, args.value, fmt=args.fmt, unit=args.unit,
            source=args.source, data=args.data)
    log.write()


def _cmd_set_interval(args):
    log = ResultsLog(args.file, run=json.loads(Path(args.run).read_text()) if args.run else None)
    log.set_interval(args.name, args.median, args.lo, args.hi, fmt=args.fmt,
                     unit=args.unit, source=args.source, data=args.data)
    log.write()


def _cmd_list(args):
    log = ResultsLog(args.file)
    for name, e in sorted(log.entries.items()):
        print(f"{name:30s} {log.display(e):30s} {e.get('source')} [{e.get('date')}]")


def _cmd_check(args):
    """Check supported explicit result uses in one trusted source file."""
    log = ResultsLog(args.file)
    log.validate()
    if Path(args.file).read_text() != log.render():
        raise ValueError("generated macros do not match the result record")
    with open(args.texfile) as f:
        text = f.read()
    text = re.sub(r"(?m)(?<!\\)%[^\n]*", "", text)
    commands = re.findall(r"\\result\b", text)
    matches = re.findall(r"\\result\s*\{([A-Za-z]+)\}", text)
    if len(commands) != len(matches):
        raise ValueError("unsupported result-use syntax")
    used = set(matches)
    missing = sorted(used - set(log.entries))
    for name in missing:
        print(f"UNDEFINED result macro: {name}")
    if missing:
        sys.exit(1)
    print(f"ok: {len(used)} \\result{{}} uses all defined")


def main():
    p = argparse.ArgumentParser(prog="texresults", description=__doc__)
    p.add_argument("--file", default="macros_results.tex",
                   help="results macro file (default: macros_results.tex)")
    p.add_argument("--run", help="JSON completed-run manifest for recording results")
    # Existing subcommands retain the upstream interface.
    sub = p.add_subparsers(dest="cmd")

    s = sub.add_parser("set", help="log a scalar result")
    s.add_argument("name")
    s.add_argument("value", type=float)
    s.add_argument("--fmt", default=None, help="python format spec, e.g. .2f")
    s.add_argument("--unit", default=None, help=r"latex unit suffix, e.g. \,M_\odot")
    s.add_argument("--source", default=None, help="script that computed it")
    s.add_argument("--data", default=None, help="input data file")
    s.set_defaults(func=_cmd_set)

    s = sub.add_parser("set-interval", help="log median + credible interval")
    s.add_argument("name")
    s.add_argument("median", type=float)
    s.add_argument("lo", type=float)
    s.add_argument("hi", type=float)
    s.add_argument("--fmt", default=None)
    s.add_argument("--unit", default=None)
    s.add_argument("--source", default=None)
    s.add_argument("--data", default=None)
    s.set_defaults(func=_cmd_set_interval)

    s = sub.add_parser("list", help="list logged results with provenance")
    s.set_defaults(func=_cmd_list)

    s = sub.add_parser("check", help="verify all \\result{} uses are defined")
    s.add_argument("texfile")
    s.set_defaults(func=_cmd_check)

    args = p.parse_args()
    if not getattr(args, "func", None):
        p.error("a subcommand is required (set, set-interval, list, check)")
    args.func(args)


if __name__ == "__main__":
    main()
